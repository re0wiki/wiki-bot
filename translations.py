from enum import StrEnum
from typing import NamedTuple


class Source(StrEnum):
    OFFICIAL_HANS = "官简"  # 官方简体中文（天闻角川）
    OFFICIAL_HANT = "官繁"  # 官方繁体中文（台版）
    FAN = "民间"  # 民间译名


class Variant(NamedTuple):
    text: str  # 写法（字面）或匹配模式（含 `[`/`(?` 正则构造时按正则解释，经 p2st 简繁展开）
    source: Source


V = Variant


class Entry(NamedTuple):
    std: Variant  # 标准名（官方简中写法 + 来源 + 可选匹配模式）
    ja: str = ""  # 日文原名
    en: str = ""  # 英文写法（无需对应 en 站条目）
    cat: str = ""  # 角色/术语/…（wiki 伪命名空间前缀）
    full_name: str = (
        ""  # 角色全名（名·姓 或 称呼→真名）；仅供一次性移动与数据参考，不进替换链
    )
    aliases: tuple[Variant, ...] = ()  # 显式别名（组外异写）：V(写法, Source.X)
    note: str = ""


def alias_texts(e: Entry) -> tuple[str, ...]:
    """别名的纯文本形式（剥离 Variant 标注）。"""
    return tuple(a.text if isinstance(a, Variant) else a for a in e.aliases)


