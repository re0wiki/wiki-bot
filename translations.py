    cat: str = ""  # 角色/术语/…（wiki 伪命名空间前缀）
    aliases: tuple[
        Variant | str, ...
    ] = ()  # 显式别名（组外异写；来源/段标注用 V("X", source, part)）
    main: bool = True  # False = 不进 translation_names 主列表（2字短名等防误判），别名仍生成精确对
